class always_three {
    public static void main(String[] args) {
        int x = 1290819;
        int temp = x;
        System.out.println(x);
        x *= 2;
        System.out.println(x);
        x += 6;
        System.out.println(x);
        x /= 2;
        System.out.println(x);
        x -= temp;
        System.out.println(x);
    }
}